class RelationalDemo{
   public static void main(String[] args){
      int firstNum = 7;
      int secondNum = 5;

      System.out.println(firstNum>secondNum);
      System.out.println(firstNum<secondNum);
      System.out.println(firstNum==secondNum);
      System.out.println(firstNum!=secondNum);
      System.out.println(firstNum>=secondNum);
      System.out.println(firstNum<=secondNum);
   }
}
